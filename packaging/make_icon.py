"""Write packaging/duosound.ico (all Windows sizes), the Inno Setup wizard images and
packaging/version_info.txt for the .exe build.
Run by build_exe.bat; the icon is the same one the window and tray use (duosound/ui_flet/icon.py)."""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from duosound import __version__  # noqa: E402
from duosound.help_text import AUTHOR  # noqa: E402
from duosound.ui_flet.icon import make_app_icon  # noqa: E402

big = make_app_icon(256)
big.save(HERE / "duosound.ico", sizes=[(16, 16), (20, 20), (24, 24), (32, 32), (40, 40), (48, 48), (64, 64), (128, 128), (256, 256)])

# ---------------------------------------------------------------- Inno Setup wizard images
# The left banner on the installer's Welcome / Finished pages, and the small logo on the other
# pages. Inno Setup wants BMP. Colours follow the app's warm palette (duosound/ui/theme.py).
BG_TOP, BG_BOTTOM, ACCENT, TEXT, TEXT_DIM = "#241C15", "#16120F", "#F28C2E", "#F4EADF", "#A08F80"


def _font(size: int, bold: bool = False):
    """Segoe UI at `size`, falling back to PIL's default if Windows fonts aren't readable."""
    for name in (("segoeuib.ttf", "segoeui.ttf") if bold else ("segoeui.ttf",)):
        try:
            return ImageFont.truetype(f"C:/Windows/Fonts/{name}", size)
        except OSError:
            continue
    return ImageFont.load_default()


def _centre(d: ImageDraw.ImageDraw, y: int, text: str, font, fill: str, w: int) -> None:
    box = d.textbbox((0, 0), text, font=font)
    d.text(((w - (box[2] - box[0])) // 2, y), text, font=font, fill=fill)


def wizard_banner(w: int = 384, h: int = 773) -> Image.Image:
    """Tall left-hand panel: vertical gradient, app icon, name, tagline and the author credit."""
    img = Image.new("RGB", (w, h), BG_BOTTOM)
    d = ImageDraw.Draw(img)
    top = tuple(int(BG_TOP[i:i + 2], 16) for i in (1, 3, 5))
    bot = tuple(int(BG_BOTTOM[i:i + 2], 16) for i in (1, 3, 5))
    for y in range(h):                                   # vertical gradient, top lighter
        t = y / max(1, h - 1)
        d.line([(0, y), (w, y)], fill=tuple(round(a + (b - a) * t) for a, b in zip(top, bot)))
    icon_px = int(w * 0.42)
    icon = make_app_icon(icon_px)                        # RGBA: pass it as its own mask, or the
    img.paste(icon, ((w - icon_px) // 2, int(h * 0.20)), icon)   # rounded corners come out black
    _centre(d, int(h * 0.44), "DuoSound", _font(int(w * 0.13), bold=True), TEXT, w)
    _centre(d, int(h * 0.51), "One movie, many headphones,", _font(int(w * 0.052)), TEXT_DIM, w)
    _centre(d, int(h * 0.54), "in sync.", _font(int(w * 0.052)), TEXT_DIM, w)
    d.line([(int(w * 0.25), int(h * 0.88)), (int(w * 0.75), int(h * 0.88))], fill=ACCENT, width=2)
    _centre(d, int(h * 0.90), "Created by", _font(int(w * 0.048)), TEXT_DIM, w)
    _centre(d, int(h * 0.925), AUTHOR, _font(int(w * 0.062), bold=True), ACCENT, w)
    return img


def wizard_small(size: int = 138) -> Image.Image:
    """Small logo shown top-right on the inner wizard pages."""
    img = Image.new("RGB", (size, size), BG_BOTTOM)
    pad = int(size * 0.10)
    icon = make_app_icon(size - 2 * pad)
    img.paste(icon, (pad, pad), icon)
    return img


wizard_banner().save(HERE / "wizard_banner.bmp")
wizard_small().save(HERE / "wizard_small.bmp")

